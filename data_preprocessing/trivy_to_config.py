    args = parser.parse_args()

    scan_data = json.loads(Path(args.scan).read_text())
    analysis  = json.loads(Path(args.analysis).read_text())
    prompt    = build_config_prompt(scan_data, analysis, args.description, args.name)

    print(build_intelligence_summary(scan_data, analysis))
    print()

    if args.out:
        Path(args.out).write_text(prompt)
        print(f"Prompt saved to {args.out}")
    else:
        print(prompt)
