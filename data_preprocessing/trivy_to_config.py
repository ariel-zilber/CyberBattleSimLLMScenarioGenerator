def _cve_to_vuln_name(cve_id: str, pkg_name: str, attack_vector: str) -> str:
    """Generate a CyberBattleSim-style vulnerability name from CVE data."""
    if cve_id in KNOWN_CVE_NAMES:
        return KNOWN_CVE_NAMES[cve_id][0]
    # Derive a name from package + vector
    clean_pkg = re.sub(r"[^a-zA-Z0-9]", "_", pkg_name).strip("_").title()
    vtype = "Remote" if attack_vector == "NETWORK" else "Local"
    return f"Solvability.{clean_pkg}_{vtype}_CVE_{cve_id[-4:]}"


def _cve_to_description(cve: dict) -> str:
    """Return a description string for a CVE dict."""
    if cve["cve_id"] in KNOWN_CVE_NAMES:
        return KNOWN_CVE_NAMES[cve["cve_id"]][1]
    desc = cve.get("description", "")
    if desc:
        return desc[:200]
    return (f"{cve['severity']} vulnerability in {cve['pkg_name']} "
            f"({cve['cve_id']}) — CVSS {cve['cvss_score']:.1f}")


# ── Core prompt builder ───────────────────────────────────────────────────────

def build_config_prompt(
    scan_data:    dict,
    analysis:     dict,
    description:  str,
    config_name:  str = "repo_scenario",
) -> str:
    """
    Combine Trivy scan + repo analysis + user description into a rich prompt
    for generate_template_yaml.

    Returns a string ready to be passed as `scenario_description`.
    """
    sections: List[str] = []

    # 1. User intent
    sections.append(f"=== SCENARIO INTENT ===\n{description.strip()}")

    # 2. Detected tech stack + suggested properties
    props = analysis.get("all_properties", [])
    tiers = analysis.get("tiers", {})
    svc_map = analysis.get("service_map", {})

    sections.append(_tech_stack_section(analysis, props, tiers))

    # 3. Real CVEs from Trivy
    cves = scan_data.get("top_cves", [])
    if cves:
        sections.append(_cve_section(cves))
    else:
        sections.append(
            "=== CVE DATA ===\n"
            "No Trivy CVEs found (repo may have no package manifests or no HIGH+ vulns).\n"
            "Use generic vulnerability templates appropriate for the detected tech stack."
        )

    # 4. Suggested attack flow
    sections.append(_attack_flow_section(tiers, svc_map))

    # 5. Suggested solvability vulnerabilities (YAML seed)
    vuln_seed = _vulnerability_seed(cves, svc_map, props)
    if vuln_seed:
        sections.append(f"=== SUGGESTED SOLVABILITY VULNERABILITIES (refine as needed) ===\n{vuln_seed}")

    # 6. Config name hint
    sections.append(f"=== CONFIG NAME ===\n{config_name}")

    sep = "\n\n" + "─" * 72 + "\n\n"
    return sep.join(sections)


# ── Section builders ──────────────────────────────────────────────────────────

def _tech_stack_section(analysis: dict, props: List[str], tiers: dict) -> str:
    lines = ["=== DETECTED TECH STACK (from repo + docker-compose) ==="]

    # Tiers
    if tiers:
        lines.append("\nNetwork tiers detected:")
        for tier, svcs in tiers.items():
            lines.append(f"  {tier}: {', '.join(svcs) or '(none)'}")

    # Docker services
    docker_svcs = analysis.get("docker_services", [])
    if docker_svcs:
        lines.append("\nDocker services:")
        for ds in docker_svcs:
            p = ", ".join(ds["properties"])
            lines.append(f"  {ds['name']} (image: {ds['image'] or '?'}) → [{p}]")

    # Subprojects
    subprojects = analysis.get("subprojects", [])
    if subprojects:
        lines.append("\nSubprojects:")
        for sp in subprojects[:10]:
            p = ", ".join(sp["properties"]) or "(none)"
            lines.append(f"  {sp['path']} ({sp['pkg_manager']}) → [{p}]")

    # Suggested properties
    lines.append(f"\nSuggested base_properties for identifiers:\n  {props}")

    lines.append(
        "\nIMPORTANT: Use ONLY these detected properties when writing node_group "
        "properties. Add standard ones (DomainJoined, Unpatched, NoLAPS, WDigest, "
        "breach_node) as needed."
    )
    return "\n".join(lines)


def _cve_section(cves: List[dict]) -> str:
    lines = [
        "=== REAL CVEs FROM TRIVY SCAN ===",
        "These are actual vulnerabilities found in the scanned repository.",
        "Map them to CyberBattleSim vulnerabilities in solvability_vulnerabilities.",
        "",
    ]

    # Separate by exploitability
    network_cves = [c for c in cves if c["attack_vector"] in ("NETWORK", "ADJACENT")]
    local_cves   = [c for c in cves if c["attack_vector"] not in ("NETWORK", "ADJACENT")]

    if network_cves:
        lines.append("REMOTE-exploitable (use as remote_access or lateral movement vulns):")
        for c in network_cves[:8]:
            lines.append(
                f"  [{c['severity']}] {c['cve_id']} — {c['pkg_name']} "
                f"CVSS={c['cvss_score']:.1f}  "
                f"→ success_rate={c['success_rate']:.2f}, cost={c['exploit_cost']:.1f}"
            )
            if c.get("description"):
                lines.append(f"    {c['description'][:150]}")

    if local_cves:
        lines.append("\nLOCAL-only (use as post-exploitation or escalation vulns):")
        for c in local_cves[:6]:
            lines.append(
                f"  [{c['severity']}] {c['cve_id']} — {c['pkg_name']} "
                f"CVSS={c['cvss_score']:.1f}"
            )

    return "\n".join(lines)


def _attack_flow_section(tiers: dict, svc_map: dict) -> str:
    lines = [
        "=== SUGGESTED ATTACK FLOW (based on detected tiers) ===",
        "Use these as attack_flow entries. Each hop should be reachable from the previous.",
        "",
    ]

    tier_order = ["WebTier", "AppTier", "WorkerTier", "DataTier", "AuthTier"]
    present = [t for t in tier_order if t in tiers]

    if len(present) >= 2:
        for i in range(len(present) - 1):
            src_tier = present[i]
            tgt_tier = present[i + 1]
            src_svcs = tiers.get(src_tier, [])
            tgt_svcs = tiers.get(tgt_tier, [])
            src_type = _tier_to_node_type(src_tier)
            tgt_type = _tier_to_node_type(tgt_tier)
            lines.append(
                f"  {src_tier} ({', '.join(src_svcs[:3])}) → {tgt_tier} ({', '.join(tgt_svcs[:3])})"
            )
            lines.append(f"    attack_flow: source_pattern={src_type!r}, targets=[{tgt_type!r}]")
    else:
        lines.append(
            "  Single-tier or undifferentiated — define at least 2 hops:\n"
            "  e.g., WebServer → DatabaseServer → DomainController"
        )

    return "\n".join(lines)


def _tier_to_node_type(tier: str) -> str:
    return {
        "WebTier":    "WebServer",
        "AppTier":    "Workstation",
        "DataTier":   "DatabaseServer",
        "AuthTier":   "DomainController",
        "WorkerTier": "WorkerNode",
    }.get(tier, "Workstation")


def _vulnerability_seed(
    cves:    List[dict],
    svc_map: Dict[str, list],
    props:   List[str],
) -> str:
    """Generate a YAML snippet for solvability_vulnerabilities as a starting point."""
    if not cves:
        return ""

    network_cves = [c for c in cves if c["attack_vector"] in ("NETWORK", "ADJACENT")]
    local_cves   = [c for c in cves if c["attack_vector"] not in ("NETWORK", "ADJACENT")]

    lines = []

    # remote_access — pick top NETWORK CVE
    if network_cves:
        c = network_cves[0]
        vname = _cve_to_vuln_name(c["cve_id"], c["pkg_name"], c["attack_vector"])
        desc  = _cve_to_description(c)
        match_props = _infer_match_properties(c["pkg_name"], c.get("target_file") or c.get("target", ""), props)
        lines += [
            "solvability_vulnerabilities:",
            "  remote_access:",
            f"    - name: {vname}",
            f"      type: REMOTE",
            f"      description: \"{desc}\"",
            f"      cost: {c['exploit_cost']:.1f}",
            f"      success_rate: {c['success_rate']:.2f}",
            f"      reward: \"RCE via {c['cve_id']} on {c['pkg_name']} — initial foothold\"",
            f"      match_properties: {match_props}",
            f"      probability: 0.75",
        ]
        if len(network_cves) > 1:
            c2 = network_cves[1]
            vname2 = _cve_to_vuln_name(c2["cve_id"], c2["pkg_name"], c2["attack_vector"])
            mp2 = _infer_match_properties(c2["pkg_name"], c2.get("target_file") or c2.get("target", ""), props)
            lines += [
                f"    - name: {vname2}",
                f"      type: REMOTE",
                f"      description: \"{_cve_to_description(c2)}\"",
                f"      cost: {c2['exploit_cost']:.1f}",
                f"      success_rate: {c2['success_rate']:.2f}",
                f"      reward: \"Foothold via {c2['cve_id']}\"",
                f"      match_properties: {mp2}",
                f"      probability: 0.60",
            ]

    # credential_leak — use a local CVE or a generic harvest
    cred_lines = ["  credential_leak:"]
    if local_cves:
        c = local_cves[0]
        vname = _cve_to_vuln_name(c["cve_id"], c["pkg_name"], "LOCAL")
        mp = _infer_match_properties(c["pkg_name"], c.get("target_file") or c.get("target", ""), props)
        cred_lines += [
            f"    - name: {vname}",
            f"      type: LOCAL",
            f"      description: \"Local privilege escalation or credential theft via {c['cve_id']}\"",
            f"      cost: {c['exploit_cost']:.1f}",
            f"      success_rate: {c['success_rate']:.2f}",
            f"      reward: \"Credentials harvested\"",
            f"      match_properties: {mp}",
            f"      probability: 0.80",
        ]
    else:
        cred_lines += [
            "    - name: Local.CredentialHarvest.ConfigFiles",
            "      type: LOCAL",
            "      description: \"Read plaintext credentials from config files on compromised host\"",
            "      cost: 0.5",
            "      success_rate: 0.85",
            "      reward: \"Credentials found in configuration files\"",
            "      match_properties: [Unpatched]",
            "      probability: 0.90",
        ]
    lines.extend(cred_lines)

    # goal_access placeholder
    lines += [
        "  goal_access:",
        "    - name: Solvability.GoalService_Compromise",
        "      type: LOCAL",
        "      description: \"Compromise the target goal service using harvested credentials\"",
        "      cost: 1.0",
        "      success_rate: 0.70",
        "      reward: \"Goal node compromised\"",
        "      match_properties: []   # set to the goal service properties",
        "      is_goal: true",
        "      probability: 0.75",
    ]

    return "\n".join(lines)


def _infer_match_properties(pkg_name: str, target_file: str, all_props: List[str]) -> str:
    """Guess match_properties from package name and target file path."""
    from repo_analyzer import packages_to_props
    guessed = packages_to_props([pkg_name.lower()])
    # Intersect with what's actually in the repo
    matched = sorted(guessed & set(all_props))
    if not matched:
        # Fall back to a generic one from the target file
        if "java" in target_file.lower() or "pom" in target_file.lower():
            matched = ["Java"]
        elif "python" in target_file.lower() or "requirements" in target_file.lower():
            matched = ["Python"]
        elif "node" in target_file.lower() or "package" in target_file.lower():
            matched = ["NodeJS"]
        else:
            matched = ["Unpatched"]
    return str(matched)


# ── Intelligence summary (for human + LLM) ───────────────────────────────────

def build_intelligence_summary(scan_data: dict, analysis: dict) -> str:
    """A concise one-page summary for display in the MCP tool response."""
    cves  = scan_data.get("top_cves", [])
    props = analysis.get("all_properties", [])
    tiers = analysis.get("tiers", {})
    lines = [
        "┌─────────────────────────────────────────────────────────────────┐",
        "  REPO INTELLIGENCE SUMMARY",
        "├─────────────────────────────────────────────────────────────────┤",
        f"  CVEs found    : {scan_data.get('cve_count', 0)}  "
        f"(Critical={scan_data.get('critical', 0)}, High={scan_data.get('high', 0)}, "
        f"Network-exploitable={scan_data.get('network_exploitable', 0)})",
        f"  Pkg managers  : {', '.join(scan_data.get('pkg_managers', []))}",
        f"  Properties    : {', '.join(props[:15])}{'...' if len(props) > 15 else ''}",
        f"  Tiers         : {', '.join(tiers.keys())}",
        "├─────────────────────────────────────────────────────────────────┤",
        "  TOP CVEs:",
    ]
    for c in cves[:5]:
        lines.append(
            f"  [{c['severity']:<8}] {c['cve_id']}  {c['pkg_name']}  "
            f"CVSS={c['cvss_score']:.1f}  AV={c['attack_vector']}"
        )
    lines.append("└─────────────────────────────────────────────────────────────────┘")
    return "\n".join(lines)


