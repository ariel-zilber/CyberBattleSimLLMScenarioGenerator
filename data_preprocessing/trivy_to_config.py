"""
tools/trivy_to_config.py
========================
Converts Trivy scan results + repo analysis into a rich intelligence prompt
that the LLM uses to generate a grounded CyberBattleSim domain config YAML.

Rather than generating the YAML directly (brittle), this module produces:
  1. A structured intelligence report (CVEs, tech stack, attack surface)
  2. A formatted prompt string ready for generate_template_yaml
  3. Seed snippets for solvability_vulnerabilities (for the LLM to refine)

Usage (standalone):
    python tools/trivy_to_config.py \\
        --scan scan.json \\
        --analysis analysis.json \\
        --description "Web app with AD backend" \\
        --out prompt.txt
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Dict, List, Optional, Tuple

# ── Pre-built dataset loader ──────────────────────────────────────────────────

_VULN_DB_DIR = Path(__file__).resolve().parent.parent / "data" / "vulnerability_db"
_BITNAMI_CVE_PATH     = _VULN_DB_DIR / "bitnami_cves.json"
_BITNAMI_CHART_PATH   = _VULN_DB_DIR / "bitnami_chart_analysis.json"


def load_bitnami_dataset() -> tuple[dict, dict]:
    """
    Load the pre-built Bitnami CVE dataset and chart analysis from
    data/vulnerability_db/.  Returns (scan_data, analysis_data).
    Both files are generated by running:
        tools/trivy_scanner.py  (image scans)
        tools/repo_analyzer.py  (chart structure)
    """
    scan_data: dict = {"top_cves": [], "cve_count": 0, "critical": 0, "high": 0,
                       "network_exploitable": 0, "pkg_managers": ["helm"]}
    analysis_data: dict = {"helm_charts": [], "all_properties": [], "tiers": {},
                           "service_map": {}, "subprojects": [], "docker_services": []}

    if _BITNAMI_CVE_PATH.exists():
        raw = json.loads(_BITNAMI_CVE_PATH.read_text())
        cves = raw.get("cves", [])
        scan_data = {
            "repo_url":            "https://github.com/bitnami/charts",
            "cve_count":           len(cves),
            "critical":            sum(1 for c in cves if c.get("severity") == "CRITICAL"),
            "high":                sum(1 for c in cves if c.get("severity") == "HIGH"),
            "network_exploitable": sum(1 for c in cves if c.get("attack_vector") == "NETWORK"),
            "pkg_managers":        raw.get("charts_scanned", []),
            "top_cves":            sorted(cves, key=lambda c: c.get("cvss_score", 0), reverse=True)[:30],
        }

    if _BITNAMI_CHART_PATH.exists():
        analysis_data = json.loads(_BITNAMI_CHART_PATH.read_text())

    return scan_data, analysis_data


def filter_dataset_for_charts(
    scan_data: dict,
    analysis_data: dict,
    chart_names: List[str],
) -> tuple[dict, dict]:
    """
    Filter the full Bitnami dataset to only CVEs and charts matching the
    requested subset (e.g. ['postgresql', 'redis', 'nginx']).
    """
    name_set = {n.lower() for n in chart_names}

    filtered_cves = [
        c for c in scan_data.get("top_cves", [])
        if c.get("chart", "").lower() in name_set
    ]
    filtered_charts = [
        hc for hc in analysis_data.get("helm_charts", [])
        if hc.get("name", "").lower() in name_set
    ]

    all_props = sorted({p for hc in filtered_charts for p in hc.get("properties", [])})

    filtered_scan = {**scan_data,
                     "top_cves": sorted(filtered_cves, key=lambda c: c.get("cvss_score", 0), reverse=True),
                     "cve_count": len(filtered_cves)}
    filtered_analysis = {**analysis_data,
                         "helm_charts": filtered_charts,
                         "all_properties": all_props}
    return filtered_scan, filtered_analysis


